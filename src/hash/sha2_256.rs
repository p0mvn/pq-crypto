    fn to_byte_encodes_every_byte_as_a_zero_padded_big_endian_integer() {
        for value in 0..=u8::MAX {
            let encoded = to_byte(value);
            assert_eq!(&encoded[..31], &[0u8; 31]);
            assert_eq!(encoded[31], value);
        }
    }

